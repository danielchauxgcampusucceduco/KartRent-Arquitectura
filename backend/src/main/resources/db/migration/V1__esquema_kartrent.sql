-- Esquema de KartRent. Compatible con PostgreSQL 16 y H2 (modo PostgreSQL) para pruebas.

CREATE TABLE clientes (
    documento           VARCHAR(20)  PRIMARY KEY,
    nombre              VARCHAR(120) NOT NULL,
    correo              VARCHAR(120),
    telefono            VARCHAR(30),
    fecha_nacimiento    DATE         NOT NULL,
    exoneracion_firmada BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_exoneracion   DATE
);

CREATE TABLE tarifas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_kart      VARCHAR(20)    NOT NULL,
    valor_por_cupo NUMERIC(12, 2) NOT NULL CHECK (valor_por_cupo > 0),
    vigente_desde  DATE           NOT NULL
);

CREATE TABLE sesiones (
    codigo           VARCHAR(20) PRIMARY KEY,
    hora_inicio      TIMESTAMP   NOT NULL,
    duracion_minutos INT         NOT NULL CHECK (duracion_minutos > 0),
    cupos_maximos    INT         NOT NULL CHECK (cupos_maximos > 0),
    cupos_vendidos   INT         NOT NULL DEFAULT 0,
    tipo_kart        VARCHAR(20) NOT NULL,
    estado           VARCHAR(20) NOT NULL,
    inicio_real      TIMESTAMP,
    fin_real         TIMESTAMP,
    CONSTRAINT ck_cupos CHECK (cupos_vendidos >= 0 AND cupos_vendidos <= cupos_maximos)
);

CREATE TABLE reservas (
    codigo            UUID           PRIMARY KEY,
    documento_cliente VARCHAR(20)    NOT NULL REFERENCES clientes (documento),
    codigo_sesion     VARCHAR(20)    NOT NULL REFERENCES sesiones (codigo),
    fecha_creacion    TIMESTAMP      NOT NULL,
    cantidad_cupos    INT            NOT NULL CHECK (cantidad_cupos > 0),
    valor_total       NUMERIC(12, 2) NOT NULL,
    estado            VARCHAR(20)    NOT NULL,
    vence_retencion   TIMESTAMP      NOT NULL
);
CREATE INDEX ix_reservas_sesion ON reservas (codigo_sesion, estado);

CREATE TABLE transponders (
    codigo        VARCHAR(20) PRIMARY KEY,
    nivel_bateria INT         NOT NULL DEFAULT 100,
    activo        BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE karts (
    numero               INT           PRIMARY KEY,
    tipo                 VARCHAR(20)   NOT NULL,
    estado               VARCHAR(20)   NOT NULL,
    kilometraje          NUMERIC(10, 3) NOT NULL DEFAULT 0,
    horas_motor          NUMERIC(10, 3) NOT NULL DEFAULT 0,
    horas_desde_servicio NUMERIC(10, 3) NOT NULL DEFAULT 0,
    codigo_transponder   VARCHAR(20) UNIQUE REFERENCES transponders (codigo)
);

CREATE TABLE asignaciones (
    codigo_sesion      VARCHAR(20)  NOT NULL REFERENCES sesiones (codigo),
    numero_parrilla    INT          NOT NULL,
    codigo_reserva     UUID         NOT NULL REFERENCES reservas (codigo),
    documento_piloto   VARCHAR(20)  NOT NULL REFERENCES clientes (documento),
    nombre_piloto      VARCHAR(120) NOT NULL,
    numero_kart        INT          NOT NULL REFERENCES karts (numero),
    codigo_transponder VARCHAR(20),
    ultimo_paso        TIMESTAMP,
    PRIMARY KEY (codigo_sesion, numero_parrilla)
);

CREATE TABLE vueltas (
    codigo_sesion   VARCHAR(20) NOT NULL,
    numero_parrilla INT         NOT NULL,
    numero_vuelta   INT         NOT NULL,
    marca_tiempo    TIMESTAMP   NOT NULL,
    tiempo_ms       BIGINT      NOT NULL,
    PRIMARY KEY (codigo_sesion, numero_parrilla, numero_vuelta),
    FOREIGN KEY (codigo_sesion, numero_parrilla) REFERENCES asignaciones (codigo_sesion, numero_parrilla)
);

CREATE TABLE pagos (
    referencia     VARCHAR(80)    PRIMARY KEY,
    codigo_reserva UUID           NOT NULL REFERENCES reservas (codigo),
    monto          NUMERIC(12, 2) NOT NULL,
    metodo         VARCHAR(30)    NOT NULL,
    aprobado       BOOLEAN        NOT NULL,
    fecha_pago     TIMESTAMP      NOT NULL
);

CREATE TABLE facturas (
    numero         VARCHAR(20)    PRIMARY KEY,
    cufe           VARCHAR(96)    NOT NULL,
    codigo_reserva UUID           NOT NULL UNIQUE REFERENCES reservas (codigo),
    fecha_emision  TIMESTAMP      NOT NULL,
    subtotal       NUMERIC(12, 2) NOT NULL,
    iva            NUMERIC(12, 2) NOT NULL,
    total          NUMERIC(12, 2) NOT NULL
);

CREATE TABLE mecanicos (
    codigo_empleado VARCHAR(10)  PRIMARY KEY,
    documento       VARCHAR(20)  NOT NULL,
    nombre          VARCHAR(120) NOT NULL,
    especialidad    VARCHAR(30)
);

CREATE TABLE ordenes_mantenimiento (
    numero               VARCHAR(20)    PRIMARY KEY,
    numero_kart          INT            NOT NULL REFERENCES karts (numero),
    tipo                 VARCHAR(20)    NOT NULL,
    estado               VARCHAR(20)    NOT NULL,
    fecha_apertura       TIMESTAMP      NOT NULL,
    fecha_cierre         TIMESTAMP,
    horas_motor_al_abrir NUMERIC(10, 3) NOT NULL,
    codigo_mecanico      VARCHAR(10) REFERENCES mecanicos (codigo_empleado),
    observaciones        VARCHAR(500)
);

CREATE TABLE parametros (
    clave VARCHAR(40)  PRIMARY KEY,
    valor VARCHAR(100) NOT NULL
);

CREATE SEQUENCE seq_factura START WITH 1;
CREATE SEQUENCE seq_orden START WITH 1;
